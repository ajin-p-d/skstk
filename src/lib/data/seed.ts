// Helper to generate realistic 30-day attendance for students
export const generateInitialAttendance = (): AttendanceRecord[] => {
  const records: AttendanceRecord[] = [];
  const students = initialStudents;
  const dates: string[] = [];

  // Generate dates from Aug 15 to Sep 11, 2026 (skipping Sundays)
  for (let d = 1; d <= 11; d++) {
    const dayStr = d < 10 ? `0${d}` : `${d}`;
    dates.push(`2026-09-${dayStr}`);
  }
  for (let d = 15; d <= 31; d++) {
    dates.push(`2026-08-${d}`);
  }

  let idCounter = 1;
  dates.forEach((date) => {
    students.forEach((student) => {
      // Arun Kumar has ~92% present rate
      let status: 'present' | 'absent' | 'leave' = 'present';
      if (student.student_id === 'KAL-2026-004') {
        // Ajay has lower attendance
        status = (idCounter % 3 === 0) ? 'absent' : (idCounter % 7 === 0 ? 'leave' : 'present');
      } else if (student.student_id === 'KAL-2026-007') {
        status = (idCounter % 5 === 0) ? 'absent' : 'present';
      } else {
        // High attendance for Arun, Sneha, Rahul
        status = (idCounter % 12 === 0) ? 'absent' : (idCounter % 19 === 0 ? 'leave' : 'present');
      }

      records.push({
        id: `att-${idCounter++}`,
        student_id: student.student_id,
        student_name: student.name,
        date: date,
        batch_id: student.batch_id,
        status: status,
        marked_by: 'Gurukkal K. Chandran',
        created_at: `${date}T07:30:00Z`,
      });
    });
  });

  return records;
};
